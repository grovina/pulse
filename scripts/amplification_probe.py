# ------------------------------------------------------------------ the metric itself


def amplification_skill(mae_calibrated: float, mae_prior_mean: float) -> float:
    """``1 - MAE_calibrated / MAE_prior_mean``.

    0 exactly when calibration left the held-out prediction where the prior mean
    had it (a rejected window, or an embedding equal to the prior mean); negative
    when fitting the calibrated markers made this one worse; NaN when the baseline
    is exactly 0 (nothing to improve on).
    """
    if not mae_prior_mean > 0.0:
        return float("nan")
    return 1.0 - mae_calibrated / mae_prior_mean


def gate_skill(mae_calibrated: float, mae_prior_mean: float, sigma_obs: float) -> float:
    """benchmark.py's ``1 - MAE / max(baseline_MAE, sigma_obs)`` with the PRIOR-MEAN
    prediction as the baseline (the gate's is persistence). Not 0 for an unchanged
    embedding when the baseline is under sigma_obs: ``1 - MAE/sigma_obs`` > 0."""
    return 1.0 - mae_calibrated / max(mae_prior_mean, sigma_obs)


def is_flat(mae_prior_mean: float, marker_id: str) -> bool:
    return not mae_prior_mean >= FLAT_REL * NORM_SCALE[MARKER_INDEX[marker_id]]


def module_of(marker_id: str) -> str:
    """The module a marker belongs to (``System`` value: metabolic, appetite, stress, ...)."""
    return MARKERS[MARKER_INDEX[marker_id]].system.value


_MODULE_TAG = {"metabolic": "met", "appetite": "app", "stress": "str", "cardiovascular": "cvs",
               "thermoreg": "thm", "respiratory": "rsp", "hepatobiliary": "hpb"}


def is_cross_module(marker_id: str, calibrated: Sequence[str]) -> bool:
    """True when no calibrated marker lives in this marker's module -- the PRD's claim is
    about COUPLED modules, so insulin after a glucose calibration is the weaker case
    (same module) and cortisol, ghrelin, sbp, temp the real one."""
    return module_of(marker_id) not in {module_of(a) for a in calibrated}


def held_out_markers(
    calibrated: Sequence[str], requested: Sequence[str],
) -> tuple[list[str], list[str]]:
    """``(held_out, dropped)``: ``requested`` minus ``calibrated``, order kept.

    The held-out set is disjoint from the calibrated one by construction, so asking
    for ``glucose`` as a held-out marker of a glucose calibration cannot leak it
    back in; it is dropped and reported. Unknown ids are an error, not a skip.
    """
    unknown = [m for m in (*calibrated, *requested) if m not in MARKER_INDEX]
    if unknown:
        raise ValueError(f"unknown marker id(s): {sorted(set(unknown))}")
    cal = set(calibrated)
    kept: list[str] = []
    for m in requested:
        if m not in cal and m not in kept:
            kept.append(m)
    return kept, [m for m in requested if m in cal]


# ------------------------------------------------------------------ tallies and units


@dataclass
class Tally:
    """Sums of |error| over the scored points of one (marker, span) in one unit."""
    n: int = 0
    cal: float = 0.0       # calibrated embedding
    prior: float = 0.0     # prior-mean embedding (no calibration)
    init: float = 0.0      # the initial state carried forward (persistence)

    def add(self, truth: np.ndarray, cal: np.ndarray, prior: np.ndarray, init: float) -> None:
        self.n += int(truth.shape[0])
        self.cal += float(np.abs(cal - truth).sum())
        self.prior += float(np.abs(prior - truth).sum())
        self.init += float(np.abs(init - truth).sum())


@dataclass
class UnitScore:
    """One synthetic patient or one real episode, under one calibrated set A."""
    unit: str
    subject: str
    accepted: bool
    reason: str
    steps: int
    cells: dict[tuple[str, str], Tally] = field(default_factory=dict)
    emb_dist_prior: float = float("nan")   # ||e_prior - e_true||, synthetic only
    emb_dist_cal: float = float("nan")     # ||e_calibrated - e_true||, synthetic only
    emb_norm: float = float("nan")
    diverged: bool = False
    seconds: float = 0.0
    channels: dict[tuple[str, str], Tally] = field(default_factory=dict)   # (channel, marker)
    hook_err: float = float("nan")     # max |rerouted full rollout - plain calibrated rollout| / NORM_SCALE

    def cell(self, marker: str, span: str) -> Tally:
        return self.cells.setdefault((marker, span), Tally())

    def mae(self, marker: str, spans: Iterable[str]) -> tuple[float, float, float, int] | None:
        """``(MAE_cal, MAE_prior, MAE_init, n)`` over ``spans``, or None without points."""
        n = sum(self.cells[(marker, s)].n for s in spans if (marker, s) in self.cells)
        if n == 0:
            return None
        parts = [self.cells[(marker, s)] for s in spans if (marker, s) in self.cells]
        return (sum(p.cal for p in parts) / n, sum(p.prior for p in parts) / n,
                sum(p.init for p in parts) / n, n)


@dataclass
class Row:
    marker: str
    role: str                  # "fit pts" | "calibrated" (A) | "cross" | "same" (held-out)
    n_points: int
    n_units: int
    mae_cal: float
    mae_prior: float
    mae_init: float
    skill: float
    skill_gate: float
    floor_active: bool         # prior-mean MAE under sigma_obs: the gate would floor it
    flat: bool
    improved: int
    worse: int
    tied: int
    skill_window: float = float("nan")
    skill_ahead: float = float("nan")

    @property
    def held_out(self) -> bool:
        return self.role in ("cross", "same")


def summarize(
    units: Sequence[UnitScore], marker: str, spans: Sequence[str], role: str,
) -> Row | None:
    """Episode-first (here: patient-first) pooled row for one marker, as the gate does:
    per-unit MAE, mean over units, then the ratio."""
    per = [(u, u.mae(marker, spans)) for u in units]
    per = [(u, m) for u, m in per if m is not None]
    if not per:
        return None
    cal = float(np.mean([m[0] for _, m in per]))
    prior = float(np.mean([m[1] for _, m in per]))
    init = float(np.mean([m[2] for _, m in per]))
    improved = worse = tied = 0
    for _, (c, p, _i, _n) in per:
        if math.isclose(c, p, rel_tol=1e-9, abs_tol=0.0):
            tied += 1
        elif c < p:
            improved += 1
        else:
            worse += 1
    sigma = sigma_obs_for(marker)

    def _span_skill(sp: str) -> float:
        s = [u.mae(marker, (sp,)) for u in units]
        s = [m for m in s if m is not None]
        if not s:
            return float("nan")
        return amplification_skill(float(np.mean([m[0] for m in s])), float(np.mean([m[1] for m in s])))

    return Row(
        marker=marker, role=role, n_points=sum(m[3] for _, m in per), n_units=len(per),
        mae_cal=cal, mae_prior=prior, mae_init=init,
        skill=amplification_skill(cal, prior), skill_gate=gate_skill(cal, prior, sigma),
        floor_active=prior < sigma, flat=is_flat(prior, marker),
        improved=improved, worse=worse, tied=tied,
        skill_window=_span_skill(SPAN_WINDOW), skill_ahead=_span_skill(SPAN_AHEAD),
    )


def per_unit_mae_matrix(
    units: Sequence[UnitScore], markers: Sequence[str], spans: Sequence[str],
) -> tuple[np.ndarray, np.ndarray]:
    """``[units, markers]`` MAEs (calibrated, prior mean); NaN where a unit has no points."""
    cal = np.full((len(units), len(markers)), np.nan)
    pri = np.full((len(units), len(markers)), np.nan)
    for i, u in enumerate(units):
        for j, m in enumerate(markers):
            r = u.mae(m, spans)
            if r is not None:
                cal[i, j], pri[i, j] = r[0], r[1]
    return cal, pri


def headline_skill(cal: np.ndarray, pri: np.ndarray, markers: Sequence[str]) -> dict[str, Any]:
    """Mean (and median) over non-flat held-out markers of the pooled per-marker skill."""
    skills: dict[str, float] = {}
    n_flat = 0
    for j, m in enumerate(markers):
        ok = ~np.isnan(pri[:, j])
        if not ok.any():
            continue
        c, p = float(np.mean(cal[ok, j])), float(np.mean(pri[ok, j]))
        if is_flat(p, m):
            n_flat += 1
            continue
        skills[m] = amplification_skill(c, p)
    vals = [v for v in skills.values() if not math.isnan(v)]
    return {
        "mean": float(np.mean(vals)) if vals else float("nan"),
        "median": float(np.median(vals)) if vals else float("nan"),
        "n_markers": len(vals), "n_flat": n_flat, "per_marker": skills,
    }


def bootstrap_headline(
    cal: np.ndarray, pri: np.ndarray, markers: Sequence[str], *,
    n_boot: int = 1000, seed: int = 0, lo: float = 5.0, hi: float = 95.0,
) -> tuple[float, float] | None:
    """Percentile interval of the headline over resampled PATIENTS (the unit of
    independence; the scored minutes inside one patient are not). None below
    ``MIN_UNITS_FOR_INTERVAL`` units."""
    u = cal.shape[0]
    if u < MIN_UNITS_FOR_INTERVAL:
        return None
    rng = np.random.default_rng(seed)
    out = []
    for _ in range(n_boot):
        idx = rng.integers(0, u, size=u)
        h = headline_skill(cal[idx], pri[idx], markers)["mean"]
        if not math.isnan(h):
            out.append(h)
    if len(out) < n_boot // 2:
        return None
    return float(np.percentile(out, lo)), float(np.percentile(out, hi))


# ------------------------------------------------------------------ models


def freeze(model: ModularPhysiologyNetwork) -> ModularPhysiologyNetwork:
    """Eval mode, no parameter grads: calibration steps ``[embedding]`` only (see
    benchmark._benchmark_worker_init)."""
    model.eval()
    for p in model.parameters():
        p.requires_grad_(False)
    return model


def give_embedding_authority(model: ModularPhysiologyNetwork, std: float, seed: int) -> int:
    """Re-draw every ALL-ZERO per-person head output matrix from ``N(0, std^2)``.

    A fresh model's per-person heads (Gb, Ib, body mass, FFA_b, mito, cortisol_b and
    the cvs/thermo/resp setpoints) end in zero-initialised matrices, so "every
    embedding is the median person" and the embedding reaches the trajectory only
    through the gut kernel. This gives the heads something to say so the full path
    can be exercised; it is a MACHINERY switch, not a trained model. Returns the
    number of matrices touched (0 means the head names changed: look at the model).
    """
    g = torch.Generator().manual_seed(seed)
    n = 0
    with torch.no_grad():
        for name, p in model.named_parameters():
            if p.ndim == 2 and _PERSON_HEAD.search(name) and bool((p == 0).all()):
                p.copy_(torch.randn(p.shape, generator=g) * std)
                n += 1
    return n


def fresh_model(seed: int = 0, authority: float = 0.0, **kwargs: Any) -> ModularPhysiologyNetwork:
    torch.manual_seed(seed)
    model = ModularPhysiologyNetwork(**kwargs)
    if authority > 0.0:
        give_embedding_authority(model, authority, seed + 2)
    return freeze(model)


def load_model(path: str) -> tuple[ModularPhysiologyNetwork, dict[str, Any]]:
    """Load a checkpoint the way scripts/rescore_artifact.py does (local path or gs://);
    ``from_checkpoint`` attaches the trained prior as ``_embedding_prior_{mean,std}``."""
    if path.startswith("gs://"):
        from pulse.train import _download_gs_uri_to_file  # lazy: pulls in the trainer
        fd, local = tempfile.mkstemp(suffix=".pt")
        os.close(fd)
        print(f"downloading {path} ...", flush=True)
        _download_gs_uri_to_file(path, local)
        path = local
    blob = torch.load(path, map_location="cpu", weights_only=False)
    return freeze(ModularPhysiologyNetwork.from_checkpoint(blob)), blob


def prior_stats(model: ModularPhysiologyNetwork) -> tuple[torch.Tensor | None, torch.Tensor | None]:
    pm = getattr(model, "_embedding_prior_mean", None)
    ps = getattr(model, "_embedding_prior_std", None)
    return (pm, ps) if pm is not None and ps is not None else (None, None)


def prior_embedding(model: ModularPhysiologyNetwork) -> torch.Tensor:
    """The no-calibration embedding: the trained prior mean, else zeros (what
    ``calibrate_embedding`` itself starts from)."""
    pm, _ = prior_stats(model)
    return pm.detach().clone().float() if pm is not None else torch.zeros(model.embedding_dim)


