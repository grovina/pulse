def run_synthetic(
    model: ModularPhysiologyNetwork, sets: Sequence[Sequence[str]], held_out: Sequence[str],
    protocol: Protocol, settings: CalibrationSettings, *, n_patients: int, seed: int,
    emb_sd: float = 0.1, emb_scale: float = 1.0, init: str = "person", obs_noise: float = 0.0,
    table: torch.Tensor | None = None, channels: bool = True, log: Any = print,
) -> list[SetResult]:
    e_prior = prior_embedding(model)
    embs = draw_embeddings(model, n_patients, seed=seed, emb_sd=emb_sd, scale=emb_scale, table=table)
    patients: list[Patient] = []
    person_ok = True
    for i, e in enumerate(embs):
        p, ok = make_patient(model, i, e, protocol, init)
        person_ok &= ok
        patients.append(p)
    if init == "person" and not person_ok:
        log("WARNING: person-specific setpoint decoders unavailable on this model; using the typical "
            "initial state for every patient")
    results = []
    for a in sets:
        b, dropped = held_out_markers(a, held_out)
        units = []
        for p in patients:
            u = score_patient(model, p, protocol, a, b, e_prior=e_prior, settings=settings,
                              obs_noise=obs_noise, noise_seed=seed, channels=channels)
            units.append(u)
            log(f"  [{'+'.join(a)}] patient {p.index + 1}/{len(patients)}  {u.seconds:5.1f}s  "
                f"{'ACCEPTED' if u.accepted else 'rejected':8} ({u.reason}, {u.steps} steps)  "
                f"||e_true||={float(p.embedding.norm()):.2f}  "
                f"dist prior->cal {u.emb_dist_prior:.3f}->{u.emb_dist_cal:.3f}")
        results.append(build_set_result("synthetic", units, a, b, dropped))
    return results


def run_real(
    model: ModularPhysiologyNetwork, episodes: Sequence[BenchmarkEpisode],
    sets: Sequence[Sequence[str]], held_out: Sequence[str] | None, settings: CalibrationSettings,
    channels: bool = True, log: Any = print,
) -> list[SetResult]:
    e_prior = prior_embedding(model)
    available = episode_markers(episodes)
    results = []
    for a in sets:
        # Unrequested held-out = every other marker with data; dropping A from it is not news.
        b, dropped = held_out_markers(a, [m for m in (held_out or available) if m in available])
        dropped = dropped if held_out else []
        if not b:
            log(f"  [{'+'.join(a)}] no held-out marker with data in these episodes; skipped")
            continue
        units = []
        for k, ep in enumerate(episodes):
            u = score_episode(model, ep, a, b, e_prior=e_prior, settings=settings, channels=channels)
            if u is None:
                log(f"  [{'+'.join(a)}] episode {ep.user_id}: fewer than 2 check-in times of {a}; skipped")
                continue
            units.append(u)
            log(f"  [{'+'.join(a)}] episode {k + 1}/{len(episodes)} {ep.user_id}  {u.seconds:6.1f}s  "
                f"{'ACCEPTED' if u.accepted else 'rejected':8} ({u.reason}, {u.steps} steps)")
        if units:
            results.append(build_set_result("real", units, a, b, dropped))
    return results


def parse_sets(text: str) -> list[tuple[str, ...]]:
    """``"glucose,glucose+hr"`` -> ``[("glucose",), ("glucose", "hr")]``."""
    sets = [tuple(m.strip() for m in grp.split("+") if m.strip()) for grp in text.split(",") if grp.strip()]
    for s in sets:
        for m in s:
            if m not in MARKER_INDEX:
                raise argparse.ArgumentTypeError(f"unknown marker {m!r}")
    return sets


def parse_markers(text: str) -> list[str]:
    ms = [m.strip() for m in text.split(",") if m.strip()]
    for m in ms:
        if m not in MARKER_INDEX:
            raise argparse.ArgumentTypeError(f"unknown marker {m!r}")
    return ms


BANNER_UNTRAINED = (
    "UNTRAINED MODEL: {what}. These numbers measure the MACHINERY (calibrate -> accept/reject -> predict ->\n"
    "score -> control), not the model. Amplification on an untrained network has no reason to be positive\n"
    "or negative, and says nothing about a trained one. Pass a checkpoint for the real question.")


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("model", nargs="?", help="checkpoint .pt (local path or gs://...); omit for a FRESH untrained model")
    ap.add_argument("--sets", type=parse_sets, default=list(DEFAULT_SETS),
                    help="calibrated sets A, comma-separated, '+' within a set (default glucose,glucose+hr)")
    ap.add_argument("--held-out", type=parse_markers, default=None,
                    help=f"held-out markers B (default {','.join(DEFAULT_HELD_OUT)} synthetic; all other "
                         "markers with data on real episodes). Anything also in A is dropped for that A.")
    ap.add_argument("--patients", type=int, default=3, help="synthetic patients (default 3)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--emb-sd", type=float, default=0.1, help="N(0, sd^2) embeddings when there is no trained prior")
    ap.add_argument("--emb-scale", type=float, default=1.0, help="multiplier on prior_std when drawing from the trained prior")
    ap.add_argument("--patients-from", choices=("prior", "table"), default="prior",
                    help="'table': the checkpoint's own trained rows (realistic covariance, but in-sample)")
    ap.add_argument("--init", choices=("person", "typical"), default="person",
                    help="synthetic initial state: this patient's own setpoints (as iter89) or NORM_CENTER")
    ap.add_argument("--noise", type=float, default=0.0, help="sensor noise on A's observations, in multiples of sigma_obs")
    ap.add_argument("--no-channels", action="store_true",
                    help="skip the transfer-channel decomposition (own / coupling / gut; ~8 extra no-grad rollouts per unit)")
    ap.add_argument("--duration", type=int, default=120)
    ap.add_argument("--cal-end", type=int, default=60)
    ap.add_argument("--obs-every", type=int, default=10)
    ap.add_argument("--score-every", type=int, default=5)
    ap.add_argument("--start-time", type=float, default=420.0, help="minute of day at t=0")
    ap.add_argument("--meal-at", type=float, default=10.0, help="meal minute (negative: fasting)")
    ap.add_argument("--steps", type=int, default=16, help="calibration max_steps (the gate runs 512)")
    ap.add_argument("--gate-settings", action="store_true",
                    help="CalibrationSettings.from_env() untouched: exactly what the gate and the server run")
    ap.add_argument("--authority", type=float, default=0.0,
                    help="FRESH model only: re-draw the zero-init per-person head outputs from N(0, STD^2)")
    ap.add_argument("--dataset", help="benchmark dataset JSON: also run PART 2 on its real episodes")
    ap.add_argument("--source", default="cgm_real", help="episode source to score (default cgm_real; 'all' for none)")
    ap.add_argument("--max-episodes", type=int, default=3, help="real episodes to score (0 = all)")
    ap.add_argument("--no-synthetic", action="store_true", help="skip PART 1")
    ap.add_argument("--json", help="write every number to this path")
    ap.add_argument("--threads", type=int, default=1, help="torch intra-op threads (1 is fastest on a loaded box)")
    args = ap.parse_args(argv)

    torch.set_num_threads(max(1, args.threads))
    trained = bool(args.model)
    if not trained and args.patients_from == "table":
        ap.error("--patients-from table needs a checkpoint (the table is part of it)")
    if trained and args.authority:
        ap.error("--authority re-draws the heads of a FRESH model; a checkpoint's heads are what is being measured")
    table = None
    if trained:
        model, blob = load_model(args.model)
        if args.patients_from == "table":
            state = blob.get("embeddings_state")
            if not state or "weight" not in state:
                raise SystemExit("--patients-from table: this checkpoint carries no embeddings_state")
            table = state["weight"].float()
        what = None
    else:
        model = fresh_model(args.seed, args.authority)
        what = (f"fresh ModularPhysiologyNetwork, seed {args.seed}, "
                + (f"per-person heads re-drawn at std {args.authority}" if args.authority > 0
                   else "per-person heads zero-initialised: the embedding reaches the trajectory only "
                        "through the gut kernel"))

    base = CalibrationSettings.from_env() if args.gate_settings else CalibrationSettings.from_env(max_steps=args.steps)
    protocol = Protocol(duration_min=args.duration, cal_end_min=args.cal_end, obs_every_min=args.obs_every,
                        score_every_min=args.score_every, start_time_minutes=args.start_time,
                        meal_at_min=args.meal_at)
    try:
        from pulse.benchmark import _git_sha
        raw = _git_sha()
        sha = raw[:12] + ("-dirty" if raw.endswith("-dirty") else "")
    except Exception:    # a header line must never be the reason a probe does not run
        sha = "unknown"
    print("amplification probe: does calibrating on markers A improve prediction of markers B it never saw?")
    print("skill = 1 - MAE_calibrated / MAE_prior_mean  (baseline: the prior-mean embedding, i.e. NOT calibrating;")
    print("        the gate's skill is 1 - MAE/max(persistence, sigma_obs)). 0 = no change, <0 = made it worse.")
    print("gate  = 1 - MAE_cal / max(MAE_prior, sigma_obs); '*' = prior-mean error already under sensor noise.")
    print("+/-/= = patients (episodes) improved / worse / tied. MAE_init = persistence from the initial state.")
    print("role: 'fit pts' / 'calibrated' = A (control: in-sample / whole scored span); held-out B is 'cross' if no A marker")
    print("      shares its module (the PRD's coupled-module claim) or 'same' if one does (insulin after glucose).")
    if not args.no_channels:
        print("CHANNELS: the calibrated embedding is shown to only part of the model (the rest keeps the prior mean):")
        for c in CHANNELS:
            print(f"  {c:<9}{CHANNEL_HELP[c]}")
    print(f"model: {sum(p.numel() for p in model.parameters()):,} parameters, "
          f"{len(model.embedding_projections)} embedding projections; code at {sha}")
    print(f"calibration: {settings_summary(base, model)}")
    if not trained:
        print(BANNER_UNTRAINED.format(what=what))

    all_results: list[SetResult] = []
    header: dict[str, Any] = {"model": args.model, "trained": trained, "settings": base.as_dict(),
                              "args": {k: v for k, v in vars(args).items() if k != "sets"},
                              "sets": ["+".join(s) for s in args.sets]}
    if not args.no_synthetic:
        b_req = args.held_out or list(DEFAULT_HELD_OUT)
        src = ("rows of the trained table" if table is not None else
               f"trained prior N(mu, sigma^2) x{args.emb_scale}" if prior_stats(model)[0] is not None else
               f"N(0, {args.emb_sd}^2)")
        print(f"\nPART 1 -- synthetic patients: {args.patients} drawn from {src}; observations and held-out truth "
              f"generated by the model itself (zero model error{'' if not args.noise else f', A noise {args.noise} sigma_obs'}).")
        print(f"protocol: {protocol.duration_min} min from {protocol.start_time_minutes / 60:.0f}:00, "
              f"{'fasting' if not protocol.meals() else f'meal {protocol.meal_carbs_g:.0f}/{protocol.meal_fats_g:.0f}/{protocol.meal_proteins_g:.0f} g C/F/P at t={protocol.meal_at_min:.0f}'}"
              f"; A observed every {protocol.obs_every_min} min over (0,{protocol.cal_end_min}], scored every "
              f"{protocol.score_every_min} min ('window' <= {protocol.cal_end_min} < 'ahead'); init={args.init}")
        t0 = time.time()
        syn = run_synthetic(model, args.sets, b_req, protocol, base, n_patients=args.patients, seed=args.seed,
                            emb_sd=args.emb_sd, emb_scale=args.emb_scale, init=args.init,
                            obs_noise=args.noise, table=table, channels=not args.no_channels)
        for r in syn:
            print(render_set(r))
        print(f"\n(synthetic part took {time.time() - t0:.0f}s)")
        all_results += syn
    if args.dataset:
        eps = load_benchmark_dataset(args.dataset)
        if args.source != "all":
            eps = [e for e in eps if e.source == args.source]
        if args.max_episodes > 0:
            eps = eps[:args.max_episodes]
        if not eps:
            print(f"\nPART 2 -- no episodes with source={args.source!r} in {args.dataset}")
        else:
            subj = len({subject_of(e.user_id) for e in eps})
            print(f"\nPART 2 -- real episodes: {len(eps)} of source {args.source!r} from {subj} subject(s) "
                  f"(read as n={subj}); calibration check-ins of A only; B scored on its own check-ins "
                  "('window') and eval measurements ('ahead').")
            t0 = time.time()
            real = run_real(model, eps, args.sets, args.held_out, base, channels=not args.no_channels)
            for r in real:
                print(render_set(r))
            print(f"\n(real part took {time.time() - t0:.0f}s)")
            all_results += real
    if all_results:
        print("\nSUMMARY (skill = 1 - MAE_cal/MAE_prior_mean; 0 = calibration changed nothing the held-out markers could feel)")
        for r in all_results:
            h = r.headline
            mean = f"{h['mean']:+.3f}" if h["n_markers"] else "  n/a "
            ctrl = f"{r.control_checkin:+.2f}" if not math.isnan(r.control_checkin) else " n/a "
            cross = (f"  cross-module {r.headline_cross['mean']:+.3f}" if r.headline_cross["n_markers"] else "")
            chan = ("" if not r.channel_cross or r.hook_err > HOOK_TOL else
                    "  via " + " ".join(f"{c} {r.channel_cross[c]:+.2f}" for c in CHANNELS[1:] if c in r.channel_cross))
            print(f"  {r.source:<9} A={'+'.join(r.a_markers):<11} accepted {r.accepted}/{len(r.units)}  "
                  f"held-out mean skill {mean} over {h['n_markers']} markers ({h['n_flat']} flat){cross}{chan}  "
                  f"control (in-sample) {ctrl} {'ok' if r.control_ok else 'NOT OK'}")
    if not trained:
        print("\n" + BANNER_UNTRAINED.format(what=what))
    if args.json:
        Path(args.json).write_text(json.dumps({**header, "results": [result_json(r) for r in all_results]}, indent=1))
        print(f"wrote {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
