@dataclass
class SetResult:
    source: str                         # "synthetic" | "real"
    a_markers: list[str]
    b_markers: list[str]
    dropped: list[str]
    units: list[UnitScore]
    rows: list[Row]
    headline: dict[str, Any]            # every non-flat held-out marker
    headline_cross: dict[str, Any]      # ... in a module none of A belongs to (the PRD's claim)
    headline_same: dict[str, Any]       # ... in an A marker's own module
    headline_accepted: dict[str, Any]   # ... over accepted windows only
    interval: tuple[float, float] | None
    interval_cross: tuple[float, float] | None
    control_checkin: float
    control_ok: bool
    control_text: str
    channel_skill: dict[str, dict[str, float]] = field(default_factory=dict)   # channel -> marker -> skill
    channel_cross: dict[str, float] = field(default_factory=dict)              # channel -> mean over x-module
    hook_err: float = float("nan")

    @property
    def accepted(self) -> int:
        return sum(u.accepted for u in self.units)


_NO_HEADLINE = {"mean": float("nan"), "median": float("nan"), "n_markers": 0, "n_flat": 0, "per_marker": {}}


def build_set_result(
    source: str, units: Sequence[UnitScore], a_markers: Sequence[str],
    b_markers: Sequence[str], dropped: Sequence[str] = (),
) -> SetResult:
    rows: list[Row] = []
    for mk in a_markers:
        for role, spans in (("fit pts", (SPAN_CHECKIN,)), ("calibrated", SPANS_SCORED)):
            r = summarize(units, mk, spans, role)
            if r is not None:
                rows.append(r)
    held = []
    for mk in b_markers:
        r = summarize(units, mk, SPANS_SCORED, "cross" if is_cross_module(mk, a_markers) else "same")
        if r is not None:
            held.append(r)
    rows.extend(held)

    markers = [r.marker for r in held]
    cross = [r.marker for r in held if r.role == "cross"]
    same = [r.marker for r in held if r.role == "same"]
    cal, pri = per_unit_mae_matrix(units, markers, SPANS_SCORED)
    head = headline_skill(cal, pri, markers) if markers else dict(_NO_HEADLINE)
    ccal, cpri = per_unit_mae_matrix(units, cross, SPANS_SCORED)
    head_cross = headline_skill(ccal, cpri, cross) if cross else dict(_NO_HEADLINE)
    scal, spri = per_unit_mae_matrix(units, same, SPANS_SCORED)
    head_same = headline_skill(scal, spri, same) if same else dict(_NO_HEADLINE)
    acc_units = [u for u in units if u.accepted]
    acal, apri = per_unit_mae_matrix(acc_units, markers, SPANS_SCORED)
    head_acc = headline_skill(acal, apri, markers) if acc_units and markers else dict(_NO_HEADLINE)
    interval = bootstrap_headline(cal, pri, markers) if markers else None
    interval_cross = bootstrap_headline(ccal, cpri, cross) if cross else None

    fit = [r for r in rows if r.role == "fit pts" and not r.flat]
    control = float(np.mean([r.skill for r in fit])) if fit else float("nan")
    acc = sum(u.accepted for u in units)
    if acc == 0:
        ok, text = False, ("CONTROL UNINFORMATIVE: no window was accepted, so the embedding never moved and "
                           "every skill is 0 by construction. Expected on an embedding-blind model (a fresh "
                           "model's per-person heads are zero-initialised: try --authority 0.3), or when the "
                           "A window carries no evidence the hold-out can confirm.")
    elif not fit:
        ok, text = False, "CONTROL UNINFORMATIVE: every calibrated marker is flat on this model."
    elif control < CONTROL_MIN_SKILL:
        ok, text = False, (f"CONTROL FAILED: in-sample skill on the calibrated markers is {control:+.2f} "
                           f"(< {CONTROL_MIN_SKILL:.2f}). Calibration did not even fit its own data, so the "
                           "held-out numbers above are not evidence about coupling: fix this first.")
    else:
        ok, text = True, (f"control ok: in-sample skill on the calibrated markers is {control:+.2f} "
                          f"(>= {CONTROL_MIN_SKILL:.2f}).")
    if source == "real":
        # On real episodes the calibrated rows hold only the eval points, i.e. the OUT-of-sample
        # control: the iter-96 sweep found calibration worse than not calibrating on glucose and hr.
        oos = [r.skill for r in rows if r.role == "calibrated" and not r.flat and not math.isnan(r.skill)]
        if oos:
            m_oos = float(np.mean(oos))
            text += (f" Out-of-sample (eval points) the calibrated markers score {m_oos:+.2f}"
                     + ("" if m_oos >= 0 else " -- calibration is WORSE than not calibrating even on the "
                        "markers it was fit to (the iter-96 sweep finding)") + ".")
    chan: dict[str, dict[str, float]] = {c: {} for c in CHANNELS}
    for c in CHANNELS:
        for r in held:
            if r.flat:
                continue
            parts = [u.channels[(c, r.marker)] for u in units if (c, r.marker) in u.channels
                     and u.channels[(c, r.marker)].n]
            if parts:
                chan[c][r.marker] = amplification_skill(
                    float(np.mean([t.cal / t.n for t in parts])), float(np.mean([t.prior / t.n for t in parts])))
    cross_live = [r.marker for r in held if r.role == "cross" and not r.flat]
    chan_cross = {c: float(np.mean([v[m] for m in cross_live if m in v])) for c, v in chan.items()
                  if any(m in v for m in cross_live)}
    errs = [u.hook_err for u in units if not math.isnan(u.hook_err)]
    return SetResult(source, list(a_markers), list(b_markers), list(dropped), list(units), rows,
                     head, head_cross, head_same, head_acc, interval, interval_cross, control, ok, text,
                     chan, chan_cross, max(errs) if errs else float("nan"))


def _g(x: float, w: int = 9) -> str:
    return f"{'-':>{w}}" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:>{w}.3g}"


def _s(x: float, w: int = 7) -> str:
    return f"{'-':>{w}}" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:>+{w}.2f}"


def _verdict(mean: float, interval: tuple[float, float] | None, n_units: int) -> str:
    if interval is not None and interval[0] <= 0.0 <= interval[1]:
        return (f"INDISTINGUISHABLE FROM ZERO: the 90% interval over {n_units} patients spans 0 "
                f"(point estimate {mean:+.3f})")
    text = ("POSITIVE: fitting A moved B toward the truth" if mean > DEAD_BAND else
            "NEGATIVE: fitting A made B worse (error laundered, not information carried)" if mean < -DEAD_BAND
            else f"ZERO: calibration changed nothing B could feel (|skill| < {DEAD_BAND:g})")
    return text + ("" if interval is not None or n_units < 2 else
                   f" (only {n_units} patients: no interval, read the sign as anecdote)")


def _span(iv: tuple[float, float] | None) -> str:
    return f"  [90% over patients {iv[0]:+.3f}, {iv[1]:+.3f}]" if iv else ""


def render_set(res: SetResult) -> str:
    a = "+".join(res.a_markers)
    n = len(res.units)
    reasons = Counter(u.reason for u in res.units)
    lines = [
        "",
        f"=== calibrate on {a}  [{res.source}: {n} {'patients' if res.source == 'synthetic' else 'episodes'}"
        + (f", {len({u.subject for u in res.units})} subject(s)" if res.source == "real" else "") + "] ===",
        f"calibration accepted in {res.accepted}/{n} windows "
        f"({res.accepted / max(n, 1):.0%})   reasons: " + ", ".join(f"{k} x{v}" for k, v in sorted(reasons.items())),
    ]
    if res.dropped:
        lines.append(f"(dropped from the held-out set because they are calibrated here: {', '.join(res.dropped)})")
    if any(u.diverged for u in res.units):
        lines.append(f"WARNING: {sum(u.diverged for u in res.units)} calibrated trajectories were non-finite "
                     "and are scored at the physiological envelope")
    syn = [u for u in res.units if not math.isnan(u.emb_dist_cal)]
    if syn:
        ratio = [u.emb_dist_cal / u.emb_dist_prior for u in syn if u.emb_dist_prior > 0]
        closer = sum(u.emb_dist_cal < u.emb_dist_prior for u in syn if u.accepted)
        lines.append(f"embedding distance to the true embedding: prior-mean {np.mean([u.emb_dist_prior for u in syn]):.3f}"
                     f" -> calibrated {np.mean([u.emb_dist_cal for u in syn]):.3f}"
                     f" (mean ratio {np.mean(ratio):.2f}; closer in {closer}/{res.accepted} accepted)")
    lines.append(
        f"{'marker':<9}{'mod':<4}{'role':<11}{'MAE_cal':>9}{'MAE_prior':>10}{'MAE_init':>9}{'skill':>8}{'gate':>8} "
        f"{'+/-/=':>7}{'n':>6}{'window':>8}{'ahead':>8}")
    for r in res.rows:
        init = _g(r.mae_init) if r.held_out else _g(float("nan"))
        skill = "flat".rjust(8) if r.flat else _s(r.skill, 8)
        gate = ("flat".rjust(8) if r.flat else _s(r.skill_gate, 7) + ("*" if r.floor_active else " "))
        wins = f"{r.improved}/{r.worse}/{r.tied}"
        span_cols = ("-".rjust(16) if r.flat or r.role == "fit pts"
                     else _s(r.skill_window, 8) + _s(r.skill_ahead, 8))
        lines.append(f"{r.marker:<9}{_MODULE_TAG.get(module_of(r.marker), '?'):<4}{r.role:<11}{_g(r.mae_cal)}{_g(r.mae_prior, 10)}"
                     f"{init}{skill}{gate} {wins:>7}{r.n_points:>6}{span_cols}")
    h, hc, hs, ha = res.headline, res.headline_cross, res.headline_same, res.headline_accepted
    lines.append("")
    if h["n_markers"]:
        lines.append(f"HEADLINE  calibrate on {a} -> mean skill over {h['n_markers']} held-out markers = "
                     f"{h['mean']:+.3f} (median {h['median']:+.3f}){_span(res.interval)}"
                     + (f"; {h['n_flat']} flat marker(s) excluded" if h["n_flat"] else ""))
        if hc["n_markers"] or hs["n_markers"]:
            part = []
            if hc["n_markers"]:
                part.append(f"cross-module {hc['mean']:+.3f} over {hc['n_markers']} ({', '.join(hc['per_marker'])})"
                            f"{_span(res.interval_cross)}")
            if hs["n_markers"]:
                part.append(f"same-module {hs['mean']:+.3f} over {hs['n_markers']} ({', '.join(hs['per_marker'])})")
            lines.append("          " + "; ".join(part))
        if res.accepted and res.accepted < n and ha["n_markers"]:
            lines.append(f"          accepted windows only ({res.accepted}/{n}): {ha['mean']:+.3f}")
        lines.append(f"          {_verdict(h['mean'], res.interval, n)}")
    else:
        lines.append(f"HEADLINE  calibrate on {a} -> no held-out marker has signal on this model "
                     f"({h['n_flat']} flat): nothing to amplify, skill undefined")
    lines.append(f"          {res.control_text}")
    if any(res.channel_skill.get(c) for c in CHANNELS):
        if res.hook_err > HOOK_TOL:
            lines.append(f"CHANNELS  untrusted: rerouting every module's projection to the calibrated embedding does "
                         f"not reproduce the plain calibrated rollout (max |diff|/NORM_SCALE {res.hook_err:.2g} > "
                         f"{HOOK_TOL:g}), so the model reads the embedding somewhere else too. Skipped.")
        else:
            live = [r for r in res.rows if r.held_out and not r.flat]
            lines.append("")
            lines.append("CHANNELS  skill vs prior mean when only part of the model sees the calibrated embedding "
                         "(not additive)")
            lines.append(f"{'marker':<9}{'mod':<4}{'role':<7}" + "".join(f"{c:>10}" for c in CHANNELS))
            for r in live:
                lines.append(f"{r.marker:<9}{_MODULE_TAG.get(module_of(r.marker), '?'):<4}{r.role:<7}"
                             + "".join(_s(res.channel_skill[c].get(r.marker, float('nan')), 10) for c in CHANNELS))
            if res.channel_cross:
                lines.append(f"{'mean over cross-module markers':<20}"
                             + "".join(_s(res.channel_cross.get(c, float('nan')), 10) for c in CHANNELS))
            lines.append(f"(reroute check: max |diff|/NORM_SCALE {res.hook_err:.1e})")
    return "\n".join(lines)


def settings_summary(st: CalibrationSettings, model: ModularPhysiologyNetwork) -> str:
    pm, ps = prior_stats(model)
    prior = (f"trained prior (diag N, weight {st.prior_weight})" if pm is not None
             else f"iso-L2 {st.l2_weight} toward the start (no trained prior)")
    return (f"max_steps={st.max_steps} lr={st.lr} patience={st.patience} holdout={st.holdout_fraction:.0%} "
            f"accept>={st.accept_rel_improvement:.0%} huber={st.huber_delta} soft_norm={st.soft_norm_weight}"
            f"@{st.soft_norm_radius} max_norm={st.max_norm} prior: {prior}")


def result_json(res: SetResult) -> dict[str, Any]:
    def clean(x: Any) -> Any:
        if isinstance(x, float) and (math.isnan(x) or math.isinf(x)):
            return None
        if isinstance(x, dict):
            return {str(k): clean(v) for k, v in x.items()}
        if isinstance(x, (list, tuple)):
            return [clean(v) for v in x]
        return x
    return clean({
        "source": res.source, "a_markers": res.a_markers, "b_markers": res.b_markers,
        "accepted": res.accepted, "units": len(res.units),
        "reasons": dict(Counter(u.reason for u in res.units)),
        "headline": res.headline, "headline_cross_module": res.headline_cross,
        "headline_same_module": res.headline_same, "headline_accepted": res.headline_accepted,
        "interval90": list(res.interval) if res.interval else None,
        "interval90_cross_module": list(res.interval_cross) if res.interval_cross else None,
        "control_checkin_skill": res.control_checkin, "control_ok": res.control_ok,
        "channels": res.channel_skill, "channels_cross_module_mean": res.channel_cross,
        "channel_reroute_err": res.hook_err,
        "rows": [r.__dict__ for r in res.rows],
        "unit_detail": [{
            "unit": u.unit, "accepted": u.accepted, "reason": u.reason, "steps": u.steps,
            "emb_dist_prior": u.emb_dist_prior, "emb_dist_cal": u.emb_dist_cal,
            "emb_norm": u.emb_norm, "seconds": u.seconds,
            # per (marker, span) sums of |error|: enough to redo any pooled number offline
            "cells": {f"{mk}/{sp}": {"n": t.n, "cal": t.cal, "prior": t.prior, "init": t.init}
                      for (mk, sp), t in u.cells.items()},
            "channel_cells": {f"{ch}/{mk}": {"n": t.n, "cal": t.cal, "prior": t.prior}
                              for (ch, mk), t in u.channels.items()},
        } for u in res.units],
    })


