@dataclass(frozen=True)
class Protocol:
    """One short synthetic day. A is observed over ``(0, cal_end_min]`` every
    ``obs_every_min``; everything is scored every ``score_every_min`` over
    ``(0, duration_min)`` -- split into ``window`` (<= cal_end) and ``ahead``."""
    duration_min: int = 120
    cal_end_min: int = 60
    obs_every_min: int = 10
    score_every_min: int = 5
    start_time_minutes: float = 420.0
    meal_at_min: float | None = 10.0       # None / negative: fasting
    meal_carbs_g: float = 60.0
    meal_fats_g: float = 10.0
    meal_proteins_g: float = 15.0
    # Explicit external inputs for every minute (awake, at rest). With them the only way the
    # embedding reaches the dynamics is the per-module projections, as in the gate's masked
    # episodes; with None the model substitutes defaults that READ the embedding directly.
    sleep_wake: float = 1.0
    activity: float = 0.0

    def __post_init__(self) -> None:
        if not 0 < self.cal_end_min < self.duration_min:
            raise ValueError("need 0 < cal_end_min < duration_min")
        if len(self.obs_times()) < 3:
            raise ValueError("need >= 3 check-in times (calibration holds the last ~20% out)")

    def masks(self) -> tuple[torch.Tensor, torch.Tensor]:
        return (torch.full((self.duration_min,), float(self.sleep_wake)),
                torch.full((self.duration_min,), float(self.activity)))

    def meals(self) -> list[MealEvent]:
        if self.meal_at_min is None or self.meal_at_min < 0:
            return []
        return [MealEvent(time=float(self.meal_at_min), carbs=self.meal_carbs_g,
                          fats=self.meal_fats_g, proteins=self.meal_proteins_g)]

    def obs_times(self) -> list[int]:
        return list(range(self.obs_every_min, self.cal_end_min + 1, self.obs_every_min))

    def score_times(self) -> list[int]:
        return list(range(self.score_every_min, self.duration_min, self.score_every_min))

    def span_times(self) -> dict[str, list[int]]:
        st = self.score_times()
        return {SPAN_CHECKIN: self.obs_times(),
                SPAN_WINDOW: [t for t in st if t <= self.cal_end_min],
                SPAN_AHEAD: [t for t in st if t > self.cal_end_min]}


@dataclass
class Patient:
    index: int
    embedding: torch.Tensor        # the true embedding
    initial_state: torch.Tensor
    truth: torch.Tensor            # [duration, STATE_DIM], the model's own trajectory


def draw_embeddings(
    model: ModularPhysiologyNetwork, n: int, *, seed: int, emb_sd: float = 0.1,
    scale: float = 1.0, table: torch.Tensor | None = None,
) -> list[torch.Tensor]:
    """``n`` true embeddings: rows of the trained table if given, else
    ``prior_mean + scale * prior_std * z`` when the model carries a prior, else
    ``N(0, emb_sd^2)``. One generator, drawn per patient, so patient i is the same
    patient whatever ``n`` is."""
    g = torch.Generator().manual_seed(seed)
    pm, ps = prior_stats(model)
    out = []
    for i in range(n):
        z = torch.randn(model.embedding_dim, generator=g)
        if table is not None:
            out.append(table[i % table.shape[0]].detach().clone().float())
        elif pm is not None:
            out.append((pm + scale * ps * z).float())
        else:
            out.append((emb_sd * z).float())
    return out


def person_initial_state(
    model: ModularPhysiologyNetwork, embedding: torch.Tensor,
) -> tuple[torch.Tensor, bool]:
    """NORM_CENTER with glucose / hr / hrv / sbp / dbp at THIS person's setpoints, decoded by
    the modules themselves (A1 moved them to log space; iter89_recovery_test.py does the
    same). ``(state, ok)``: not ok means a decoder is gone and the typical state came back."""
    st = torch.tensor(NORM_CENTER, dtype=torch.float32)
    try:
        with torch.no_grad():
            e_met = model.embedding_projections["metabolic"](embedding)
            e_cvs = model.embedding_projections["cardiovascular"](embedding)
            gb = float(model.metabolic.glucose_setpoint_raw(e_met))
            hr, hrv, sbp, dbp = (float(x) for x in model.cardiovascular.setpoints_raw(e_cvs))
    except (AttributeError, KeyError, TypeError, ValueError):
        return st, False
    for marker, v in (("glucose", gb), ("hr", hr), ("hrv", hrv), ("sbp", sbp), ("dbp", dbp)):
        st[MARKER_INDEX[marker]] = v
    return st, True


def rollout(
    model: ModularPhysiologyNetwork, state: torch.Tensor, embedding: torch.Tensor, protocol: Protocol,
) -> torch.Tensor:
    sw, act = protocol.masks()
    with torch.no_grad():
        return integrate(
            model=model, initial_state=state, embedding=embedding, n_steps=protocol.duration_min,
            dt=1.0, start_time_minutes=protocol.start_time_minutes, meals=protocol.meals(),
            sleep_wake=sw, activity=act,
        )


def make_patient(
    model: ModularPhysiologyNetwork, index: int, embedding: torch.Tensor, protocol: Protocol,
    init: str = "person",
) -> tuple[Patient, bool]:
    """A synthetic patient and whether the person-specific initial state was available."""
    ok = True
    if init == "person":
        state, ok = person_initial_state(model, embedding)
    else:
        state = torch.tensor(NORM_CENTER, dtype=torch.float32)
    return Patient(index, embedding, state, rollout(model, state, embedding, protocol)), ok


def _finite_or_clipped(traj: torch.Tensor) -> tuple[torch.Tensor, bool]:
    """A calibrated embedding that detonates the forward pass is the worst possible
    held-out result, not a missing one: score it at the physiological envelope."""
    if bool(torch.isfinite(traj).all()):
        return traj, False
    lo = torch.tensor(PHYSIOLOGICAL_MIN, dtype=traj.dtype)
    hi = torch.tensor(PHYSIOLOGICAL_MAX, dtype=traj.dtype)
    traj = torch.nan_to_num(traj, nan=0.0, posinf=1e30, neginf=-1e30)
    return torch.max(torch.min(traj, hi), lo), True


@contextmanager
def seen_by(model: ModularPhysiologyNetwork, override: dict[str, torch.Tensor]):
    """Inside the block, the projection of each module in ``override`` reads that embedding
    instead of the one ``integrate`` was given. The model projects the embedding per module
    with ``proj(embedding)`` (forward, the rollout plan, the gut precompute), so a pre-hook
    on the projection reroutes exactly that read and nothing else."""
    handles = []
    try:
        for name, emb in override.items():
            def pre(_module, args, emb=emb):
                x = args[0]
                return (emb.to(x.dtype).expand_as(x), *args[1:])
            handles.append(model.embedding_projections[name].register_forward_pre_hook(pre))
        yield
    finally:
        for h in handles:
            h.remove()


def channel_trajectories(
    model: ModularPhysiologyNetwork, roll: Any, e_prior: torch.Tensor, e_cal: torch.Tensor,
    a_markers: Sequence[str], b_markers: Sequence[str],
) -> dict[str, Any]:
    """Held-out trajectories when only PART of the model sees the calibrated embedding.

    Calibration moves one shared vector, and "a glucose reading constrains ghrelin" can be
    true for two different reasons: (1) the coupling graph -- A's module is now different, B
    reads A's output; (2) the shared embedding -- B's own parameters moved with the code, or
    both read the same upstream driver (the gut kernel). The table reports the sum. Here the
    rollout is run with the prior-mean embedding everywhere EXCEPT:

    * ``coupling``: A's modules       -> B can move only through coupling edges;
    * ``own[module]``: B's own module -> B moves only through its own parameters;
    * ``gut``: the gut kernel         -> only the shared meal driver moves;
    * ``every``: all of them          -> must equal the plain calibrated rollout.

    ``roll(embedding) -> [T, STATE_DIM]`` is the unit's own no-grad rollout.
    """
    names = list(model.embedding_projections)
    a_mods = {module_of(a) for a in a_markers} & set(names)
    out: dict[str, Any] = {"own": {}}
    with seen_by(model, {n: e_cal for n in names}):
        out["every"] = roll(e_prior)
    with seen_by(model, {n: e_cal for n in a_mods}):
        out["coupling"] = roll(e_prior)
    with seen_by(model, {"gut": e_cal}):
        out["gut"] = roll(e_prior)
    for mod in sorted({module_of(b) for b in b_markers} & set(names)):
        with seen_by(model, {mod: e_cal}):
            out["own"][mod] = roll(e_prior)
    return out


def tally_channels(
    unit: "UnitScore", model: ModularPhysiologyNetwork, roll: Any, e_prior: torch.Tensor,
    e_cal: torch.Tensor, pred_cal: torch.Tensor, pred_prior: torch.Tensor,
    a_markers: Sequence[str], targets: dict[str, tuple[list[int], np.ndarray]],
    initial_state: torch.Tensor,
) -> None:
    """Fill ``unit.channels[(channel, marker)]``; ``targets[marker] = (times, truth)`` are the
    held-out points to score (the dense grid for a synthetic patient, the measured points of a
    real episode)."""
    targets = {mk: tv for mk, tv in targets.items() if len(tv[0])}
    if not targets:
        return
    if torch.equal(e_cal, e_prior):          # rejected: every channel IS the prior
        ch = {"every": pred_prior, "coupling": pred_prior, "gut": pred_prior,
              "own": {module_of(b): pred_prior for b in targets}}
        unit.hook_err = 0.0
    else:
        ch = channel_trajectories(model, roll, e_prior, e_cal, a_markers, list(targets))
        scale = torch.tensor(NORM_SCALE, dtype=pred_cal.dtype)
        unit.hook_err = float(((ch["every"] - pred_cal).abs() / scale).max())
    for mk, (times, truth) in targets.items():
        j = MARKER_INDEX[mk]
        pri = pred_prior[times, j].numpy().astype(np.float64)
        trajs = {"full": pred_cal, "coupling": ch["coupling"], "gut": ch["gut"],
                 "own": ch["own"].get(module_of(mk), pred_prior)}
        for name, traj in trajs.items():
            unit.channels.setdefault((name, mk), Tally()).add(
                truth, traj[times, j].numpy().astype(np.float64), pri, float(initial_state[j]))


def score_patient(
    model: ModularPhysiologyNetwork, patient: Patient, protocol: Protocol,
    a_markers: Sequence[str], b_markers: Sequence[str], *,
    e_prior: torch.Tensor, settings: CalibrationSettings, obs_noise: float = 0.0,
    noise_seed: int = 0, channels: bool = True,
) -> UnitScore:
    """Calibrate on ``a_markers`` only, then score A (control) and ``b_markers``."""
    if set(a_markers) & set(b_markers):
        raise ValueError(f"held-out markers overlap the calibrated set: {set(a_markers) & set(b_markers)}")
    g = torch.Generator().manual_seed(noise_seed + 7919 * patient.index)
    obs = []
    for mk in a_markers:
        for t in protocol.obs_times():
            v = float(patient.truth[t, MARKER_INDEX[mk]])
            if obs_noise > 0.0:
                v += obs_noise * sigma_obs_for(mk) * float(torch.randn((), generator=g))
            obs.append(MeasurementPoint(time=t, marker_id=mk, value=v))
    # The held-out set never reaches calibration: only A's markers are observed.
    assert {o.marker_id for o in obs} == set(a_markers)

    pm, ps = prior_stats(model)
    sw, act = protocol.masks()
    t_start = time.time()
    res = calibrate_embedding(
        model, obs, patient.initial_state, protocol.meals(), protocol.duration_min,
        start_time_minutes=protocol.start_time_minutes, sleep_wake=sw, activity=act,
        prior_mean=pm, prior_std=ps, settings=settings,
    )
    pred_prior = rollout(model, patient.initial_state, e_prior, protocol)
    same = torch.equal(res.embedding, e_prior)
    pred_cal, diverged = (pred_prior, False) if same else _finite_or_clipped(
        rollout(model, patient.initial_state, res.embedding, protocol))

    unit = UnitScore(
        unit=f"synthetic-{patient.index:02d}", subject=f"synthetic-{patient.index:02d}",
        accepted=bool(res.accepted), reason=res.reason, steps=int(res.n_steps),
        emb_dist_prior=float((e_prior - patient.embedding).norm()),
        emb_dist_cal=float((res.embedding - patient.embedding).norm()),
        emb_norm=float(res.embedding.norm()), diverged=diverged,
    )
    for mk in (*a_markers, *b_markers):
        j = MARKER_INDEX[mk]
        truth = patient.truth[:, j].numpy().astype(np.float64)
        cal = pred_cal[:, j].numpy().astype(np.float64)
        pri = pred_prior[:, j].numpy().astype(np.float64)
        init = float(patient.initial_state[j])
        for span, times in protocol.span_times().items():
            if span == SPAN_CHECKIN and mk not in a_markers:
                continue
            if times:
                unit.cell(mk, span).add(truth[times], cal[times], pri[times], init)
    if channels:
        grid = protocol.score_times()
        tally_channels(
            unit, model, lambda e: rollout(model, patient.initial_state, e, protocol), e_prior,
            res.embedding, pred_cal, pred_prior, a_markers,
            {mk: (grid, patient.truth[grid, MARKER_INDEX[mk]].numpy().astype(np.float64)) for mk in b_markers},
            patient.initial_state)
    unit.seconds = time.time() - t_start
    return unit


# ------------------------------------------------------------------ real episodes


def _episode_points(ep: BenchmarkEpisode) -> tuple[list[MeasurementPoint], list[MeasurementPoint]]:
    """``(check_in_points, eval_points)``: every numeric marker in the episode's
    calibration check-ins and in its eval measurements (not just the gate's five)."""
    checkins: list[MeasurementPoint] = []
    for c in ep.calibration_check_ins:
        if not isinstance(c, dict) or c.get("time") is None:
            continue
        t = int(round(float(c["time"])))
        if not 0 <= t < ep.duration_min:
            continue
        for mk, v in (c.get("measurements") or {}).items():
            if mk in MARKER_INDEX and isinstance(v, (int, float)) and not isinstance(v, bool):
                checkins.append(MeasurementPoint(time=t, marker_id=mk, value=float(v)))
    return checkins, [p for p in ep.eval_measurements if p.marker_id in MARKER_INDEX]


def episode_markers(episodes: Sequence[BenchmarkEpisode]) -> list[str]:
    """Markers with any measurement in these episodes, in canonical order."""
    seen: set[str] = set()
    for ep in episodes:
        ci, ev = _episode_points(ep)
        seen.update(p.marker_id for p in (*ci, *ev))
    return [m for m in MARKER_IDS if m in seen]


def score_episode(
    model: ModularPhysiologyNetwork, ep: BenchmarkEpisode, a_markers: Sequence[str],
    b_markers: Sequence[str], *, e_prior: torch.Tensor, settings: CalibrationSettings,
    channels: bool = True,
) -> UnitScore | None:
    """Calibrate on A's check-ins (the gate's inputs: start time, masks, prior), score the
    rest. None when the episode has no check-in of any A marker."""
    checkins, evals = _episode_points(ep)
    a_obs = [p for p in checkins if p.marker_id in a_markers]
    if len({p.time for p in a_obs}) < 2:
        return None
    t0 = float(ep.start_time_minutes) % 1440.0 if ep.start_time_minutes is not None else 360.0
    init = torch.tensor(ep.initial_state, dtype=torch.float32)
    sw = None if ep.sleep_wake is None else torch.tensor(ep.sleep_wake[:ep.duration_min], dtype=torch.float32)
    act = None if ep.activity is None else torch.tensor(ep.activity[:ep.duration_min], dtype=torch.float32)

    pm, ps = prior_stats(model)
    t_start = time.time()
    res = calibrate_embedding(
        model, a_obs, init, ep.meals, ep.duration_min, start_time_minutes=t0,
        sleep_wake=sw, activity=act, prior_mean=pm, prior_std=ps, settings=settings,
    )

    def _roll(emb: torch.Tensor) -> torch.Tensor:
        with torch.no_grad():
            return integrate(model=model, initial_state=init, embedding=emb, n_steps=ep.duration_min,
                             dt=1.0, start_time_minutes=t0, meals=ep.meals, sleep_wake=sw, activity=act)

    pred_prior = _roll(e_prior)
    same = torch.equal(res.embedding, e_prior)
    pred_cal, diverged = (pred_prior, False) if same else _finite_or_clipped(_roll(res.embedding))

    unit = UnitScore(
        unit=ep.user_id, subject=subject_of(ep.user_id), accepted=bool(res.accepted),
        reason=res.reason, steps=int(res.n_steps), emb_norm=float(res.embedding.norm()),
        diverged=diverged,
    )
    wanted = set(a_markers) | set(b_markers)
    # A's check-ins are the in-sample control; B's check-ins (never fed to calibration)
    # are the in-window held-out points; everything in eval is later than calibration.
    for span, pts in ((SPAN_CHECKIN, [p for p in checkins if p.marker_id in a_markers]),
                      (SPAN_WINDOW, [p for p in checkins if p.marker_id in b_markers]),
                      (SPAN_AHEAD, [p for p in evals if p.marker_id in wanted])):
        for mk in {p.marker_id for p in pts}:
            sel = [p for p in pts if p.marker_id == mk]
            j = MARKER_INDEX[mk]
            ts = [p.time for p in sel]
            truth = np.array([p.value for p in sel], dtype=np.float64)
            unit.cell(mk, span).add(
                truth, pred_cal[ts, j].numpy().astype(np.float64),
                pred_prior[ts, j].numpy().astype(np.float64), float(ep.initial_state[j]))
    if channels:
        targets = {}
        for mk in b_markers:
            sel = [q for q in (*checkins, *evals) if q.marker_id == mk]
            if sel:
                targets[mk] = ([p.time for p in sel], np.array([p.value for p in sel], dtype=np.float64))
        tally_channels(unit, model, _roll, e_prior, res.embedding, pred_cal, pred_prior, a_markers,
                       targets, init)
    unit.seconds = time.time() - t_start
    return unit


