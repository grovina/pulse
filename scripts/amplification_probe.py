#!/usr/bin/env python3
"""Does calibrating on some markers improve prediction of markers it never saw?

PRD, *Why modularity*: "a single glucose reading doesn't just constrain glucose --
it propagates through the coupling graph", and *Success criteria*: "Coupling
amplifies information: observations on one module improve predictions for coupled
modules". PLAN D5 recorded that this had no number. This is the number.

THE EXPERIMENT. Calibrate the embedding on marker set A (the shared
``pulse.calibration.calibrate_embedding`` the gate and the server run; ``--steps``
caps its Adam steps for speed, ``--gate-settings`` lifts the cap), then predict a
DISJOINT held-out set B and compare with the honest baseline of not having
calibrated at all:

    skill[b] = 1 - MAE_calibrated[b] / MAE_prior_mean[b]

* The baseline is the PRIOR-MEAN embedding (the trained prior mean, else zeros),
  NOT persistence. The gate's skill is ``1 - MAE / max(persistence_MAE, sigma_obs)``
  (benchmark.py ``_build_per_marker``); this is the same shape with a different
  baseline, so 0 means "calibration changed nothing the held-out markers could
  feel", positive means fitting A moved B toward the truth, and NEGATIVE means
  fitting A made B worse -- the coupling is laundering error instead of carrying
  information. Both are reported plainly. Aggregation is the gate's too: MAE per
  patient (episode) first, then the mean over patients, then the ratio.
* ``skill`` is the raw ratio, the only form that is exactly 0 when nothing
  changed. ``gate`` is the benchmark.py form with the denominator floored at
  sigma_obs; it is flagged ``*`` when the prior-mean error is already under the
  sensor noise, where the floor hands out credit for being inside the noise rather
  than for amplifying anything. ``MAE_init`` is persistence from the initial state,
  the gate's own baseline for a marker calibration never saw, so a reader can see
  when the prior-mean baseline is itself worse than carrying the first reading
  forward. A marker whose prior-mean error is under 1e-4 of its NORM_SCALE is
  ``flat`` -- the model gives calibration nothing to move there -- and is left out
  of the headline and counted.

ACCEPTANCE IS PART OF THE RESULT. ``calibrate_embedding`` returns the initial
embedding unchanged unless the chronological hold-out (the last ~20% of the A
check-in TIMES) improved by 1%. A rejected window therefore scores skill exactly 0
on every marker, and the table counts them: a glucose-only window that is rarely
accepted cannot amplify anything. Do not confuse the two hold-outs: that one is
temporal, inside calibration, on the markers it was shown; B is held out by MARKER.

THE CONTROL. The markers that WERE calibrated on are scored too, at the check-in
times themselves (in-sample) and over the whole scored span. In-sample skill must
be clearly positive on synthetic patients the model generated itself; if it is not,
the probe is measuring nothing and that is the first thing to fix. A verdict line
says which.

CROSS- vs SAME-MODULE. The PRD claims transfer to COUPLED modules, so held-out
markers are tagged ``cross`` when no calibrated marker shares their module and
``same`` when one does (insulin after glucose, sbp after hr), and the headline is
split. ``same`` is the weak claim; ``cross`` is the PRD's.

CHANNELS. Calibration moves ONE shared vector, so a positive skill can arrive two
ways that the table adds together: through the coupling graph (A's module changed,
B reads it) or through the shared embedding (B's own parameters moved with the code,
or both read one upstream driver such as the gut kernel). The CHANNELS table (on by
default; ``--no-channels`` skips it) reruns the held-out rollout with the calibrated
embedding shown to only part of the model, by rerouting the per-module projections
the model already has: ``own`` (B's module only), ``coupling`` (A's modules only: B
can move only through coupling edges), ``gut`` (the gut kernel only: the shared meal
driver). The channels are not additive. If rerouting every projection does not
reproduce the plain rollout, the model reads the embedding somewhere else too, and
the table says so rather than printing a decomposition it cannot stand behind.

PART 1, SYNTHETIC PATIENTS (the clean case). Embeddings are drawn from the trained
prior (``prior_mean + prior_std * z``, as iter89_recovery_test.py does) when the
checkpoint carries one, else ``N(0, 0.1^2)``; each patient starts from their own
setpoints, and their observations and the held-out truth are generated by the
model ITSELF with explicit awake/rest inputs: no model error, no sensor noise
(``--noise`` adds some to A's observations), every input known. A zero or negative
number here is therefore decisive about the model's own structure -- better data
cannot fix it -- while a positive one only says the structure CAN transfer. Two
limits: a diagonal prior samples independent coordinates, so it does not sample the
correlations a real population has (``--patients-from table`` uses the checkpoint's
trained rows instead, which have them but were trained on); and 3 patients is a
machinery check, not a confidence interval (one is printed from 6).

PART 2, REAL EPISODES (``--dataset``). Per episode: calibrate on A's check-ins with
the episode's masks and start time, score the markers outside A on the episode's own
measurements -- B's calibration-window check-ins (``window``) and the eval
measurements (``ahead``) -- e.g. calibrate on glucose, score hr on the ``cgm_real``
nights. ``cgm_real`` is 14 nights of ONE subject: read it as n=1 (the output counts
subjects).

WHAT AN UNTRAINED MODEL'S NUMBERS ARE. No trained checkpoint is needed to run this,
and without one the numbers measure the MACHINERY (calibrate -> accept or reject ->
predict -> score -> control), not the model. A fresh ``ModularPhysiologyNetwork`` has
every per-person head zero-initialised (15 all-zero output matrices at this commit), so
"every embedding is the median person" and the embedding reaches the trajectory only
through the gut kernel and the appetite dynamics. Measured (seed 0, 8 patients at
sd 0.1, 120 min): the prior-mean prediction is off by 0.048 mg/dL of glucose, 0.051
uU/mL of insulin, 0.021 pg/mL of ghrelin -- and by exactly 0 in cortisol, acth, sbp,
dbp, rr and spo2. The probe finds those held-out markers ``flat`` and says so.
``--authority STD`` re-draws the zero matrices from N(0, STD^2) so the embedding can
move every module (at 0.3: glucose 0.63 mg/dL, sbp 0.99 mmHg, hr 0.73 bpm); that
exercises the whole path on a model that is still untrained. What it showed
(3 model seeds x 2 sets x 3 patients, plus one 8-patient run): a clearly positive
control (in-sample skill +0.57 to +0.90), calibration accepted in 22 of 26 windows,
and a held-out headline that is indistinguishable from zero with a sign that changes
with the seed (-0.14 to +0.16 over the six seed x set cells, mean +0.02; the 8-patient
interval spans 0), because the shared projections are random.
None of this says anything about whether a TRAINED model amplifies information. The
only thing an untrained run can establish is that the instrument works.

COST. One Adam step is one forward+backward over the whole calibration window, ~0.5-1
s per 60 minutes on a quiet core and several times that on a loaded box, so the defaults
are small: 3 patients x 2 sets, 120 min, 16 Adam steps, channels on = ~90 s alone on a
4-core box at load ~15 (~8 min when five runs share it; the first backward in a process
can cost minutes more on a cold box). Scale up with ``--patients``, ``--steps`` and
``--gate-settings`` (the gate's own 512 steps with patience; minutes per patient).

Usage:
    python scripts/amplification_probe.py                         # fresh model, machinery
    python scripts/amplification_probe.py --authority 0.3         # fresh, heads live
    python scripts/amplification_probe.py MODEL.pt --patients 12 --gate-settings --json amp.json
    python scripts/amplification_probe.py MODEL.pt --dataset BENCH.json --source cgm_real \\
        --sets glucose --max-episodes 14 --gate-settings --no-synthetic
"""

